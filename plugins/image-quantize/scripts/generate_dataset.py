def md_cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def display_path(path, anchor):
    try:
        return path.relative_to(anchor).as_posix()
    except ValueError:
        return path.as_posix()


def render_manifest(rows, real):
    real_files = real.get("files", [])
    lines = []
    lines.append("# Seer Image Quantization - SPEC-003 Phase 0 Dataset")
    lines.append("")
    lines.append("Generated by `scripts/generate_dataset.py` (28 files, Python standard library")
    lines.append("only) and `scripts/generate_animated_webp.py` (one animated WebP file, which")
    lines.append("needs Pillow because the standard library has no WebP encoder). Both scripts")
    lines.append("are deterministic, and every fixture is dedicated to the public domain")
