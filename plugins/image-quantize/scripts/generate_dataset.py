"""Deterministic synthetic image fixture generator for SPEC-003 Phase 0.

This script builds the fixture dataset described in SPEC-003 section 9.1 using
only the Python standard library. Every image is encoded by hand as a real,
decodable file (PNG, GIF, or TIFF); no third-party imaging library is used.

Outputs
-------
* 28 real synthetic image files (PNG / GIF / TIFF) in the output directory,
  plus the animated WebP fixture produced by ``generate_animated_webp.py``.
* A Markdown manifest with per-file byte sizes and SHA-256 checksums.
* A machine-readable ``dataset.json`` next to the manifest.

The generated bytes are fully deterministic: no wall-clock time, no unseeded
randomness, and fixed compression settings are used.
"""

