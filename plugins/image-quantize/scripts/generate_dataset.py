# --------------------------------------------------------------------------
# Tiny deterministic pseudo-random byte source (linear congruential generator).
# No ``random`` module is imported and no wall-clock value is used.
# --------------------------------------------------------------------------
def lcg_bytes(count, seed):
    state = seed & 0xFFFFFFFF
    out = bytearray()
    for _ in range(count):
        state = (1103515245 * state + 12345) & 0x7FFFFFFF
        out.append((state >> 16) & 0xFF)
    return bytes(out)


# --------------------------------------------------------------------------
# PNG encoder (colour type 2 = RGB, colour type 6 = RGBA, 8-bit, filter 0).
# --------------------------------------------------------------------------
def png_chunk(tag, payload):
    return (
        struct.pack(">I", len(payload))
        + tag
        + payload
        + struct.pack(">I", zlib.crc32(tag + payload) & 0xFFFFFFFF)
    )


def png_file(width, height, color_type, raw_pixels, extra_chunks=b""):
    bpp = 3 if color_type == 2 else 4
    row_bytes = width * bpp
    if len(raw_pixels) != row_bytes * height:
        raise ValueError("raw pixel buffer has the wrong length")
    scanlines = bytearray()
    for y in range(height):
        scanlines.append(0)  # filter type 0 (None)
        scanlines.extend(raw_pixels[y * row_bytes:(y + 1) * row_bytes])
    ihdr = struct.pack(">IIBBBBB", width, height, 8, color_type, 0, 0, 0)
    return (
        PNG_SIGNATURE
        + png_chunk(b"IHDR", ihdr)
        + extra_chunks
        + png_chunk(b"IDAT", zlib.compress(bytes(scanlines), 9))
        + png_chunk(b"IEND", b"")
    )


def exif_tiff(orientation):
    """Minimal little-endian TIFF carrying EXIF Orientation (0x0112, SHORT)."""
    header = b"II" + struct.pack("<H", 42) + struct.pack("<I", 8)
    count = struct.pack("<H", 1)
    entry = struct.pack("<HHI", 0x0112, 3, 1) + struct.pack("<I", orientation)
    next_ifd = struct.pack("<I", 0)
    return header + count + entry + next_ifd


# --------------------------------------------------------------------------
# Minimal ICC profile builder (ICC v2.1 matrix/shaper, big-endian).
# --------------------------------------------------------------------------
def s15fixed16(value):
    return struct.pack(">i", int(round(value * 65536.0)))


def xyz_type(x, y, z):
    return b"XYZ " + b"\x00" * 4 + s15fixed16(x) + s15fixed16(y) + s15fixed16(z)


def curve_type(gamma):
    value = struct.pack(">H", int(round(gamma * 256.0)))
    return b"curv" + b"\x00" * 4 + struct.pack(">I", 1) + value + b"\x00\x00"


def text_type(text):
    ascii_text = text.encode("ascii") + b"\x00"
    data = b"text" + b"\x00" * 4 + ascii_text
    while len(data) % 4:
        data += b"\x00"
    return data


def text_description_type(text):
    ascii_text = text.encode("ascii") + b"\x00"
    data = b"desc" + b"\x00" * 4
    data += struct.pack(">I", len(ascii_text)) + ascii_text
    data += struct.pack(">I", 0)  # unicode language code
    data += struct.pack(">I", 0)  # unicode string length
    data += struct.pack(">h", 0)  # scriptcode code
    data += struct.pack(">B", 0)  # scriptcode count
    data += b"\x00" * 67           # scriptcode description
    while len(data) % 4:
        data += b"\x00"
    return data


def icc_profile(description, columns, gamma=2.2):
    wtpt = (0.9642, 1.0, 0.8249)  # D50, the ICC PCS illuminant
    tags = [
        (b"cprt", text_type("Public domain, generated by generate_dataset.py")),
        (b"desc", text_description_type(description)),
        (b"wtpt", xyz_type(*wtpt)),
        (b"rXYZ", xyz_type(*columns["r"])),
        (b"gXYZ", xyz_type(*columns["g"])),
        (b"bXYZ", xyz_type(*columns["b"])),
        (b"rTRC", curve_type(gamma)),
        (b"gTRC", curve_type(gamma)),
        (b"bTRC", curve_type(gamma)),
    ]
    tags.sort(key=lambda item: item[0])

    header_size = 128
    table_size = 4 + 12 * len(tags)
    data_offset = header_size + table_size

    offsets = []
    blob = bytearray()
    for _sig, payload in tags:
        offsets.append(data_offset + len(blob))
        blob += payload
        while len(blob) % 4:
            blob += b"\x00"

    total = data_offset + len(blob)
    header = bytearray(header_size)

    def put(offset, value):
        header[offset:offset + len(value)] = value

    put(0, struct.pack(">I", total))
    put(4, b"\x00" * 4)
    put(8, struct.pack(">I", 0x02100000))  # version 2.1.0
    put(12, b"mntr")
    put(16, b"RGB ")
    put(20, b"XYZ ")
    put(24, b"\x00" * 12)  # fixed zero date/time, never a real timestamp
    put(36, b"acsp")
    put(40, b"\x00" * 4)
    put(44, struct.pack(">I", 0))
    put(48, b"\x00" * 4)
    put(52, struct.pack(">I", 0))
    put(56, b"\x00" * 8)
    put(64, struct.pack(">I", 0))  # perceptual rendering intent
    put(68, s15fixed16(wtpt[0]) + s15fixed16(wtpt[1]) + s15fixed16(wtpt[2]))
    put(80, b"\x00" * 4)
    put(84, b"\x00" * 16)
    put(100, b"\x00" * 28)

    table = struct.pack(">I", len(tags))
    for (sig, payload), offset in zip(tags, offsets):
        table += sig + struct.pack(">I", offset) + struct.pack(">I", len(payload))
    return bytes(header) + table + bytes(blob)


def iccp_chunk(profile_name, profile_bytes):
    payload = (
        profile_name.encode("ascii")
        + b"\x00"  # null terminator of the profile name
        + b"\x00"  # compression method 0 (zlib)
        + zlib.compress(profile_bytes, 9)
    )
    return png_chunk(b"iCCP", payload)


# --------------------------------------------------------------------------
# GIF89a encoder: 2-frame looped animation written without a growing LZW
# dictionary (literal codes plus periodic clear codes, all at a fixed width).
# --------------------------------------------------------------------------
def pack_lsb(codes, width):
    out = bytearray()
    accumulator = 0
    bit_count = 0
    for code in codes:
        accumulator |= code << bit_count
        bit_count += width
        while bit_count >= 8:
            out.append(accumulator & 0xFF)
            accumulator >>= 8
            bit_count -= 8
    if bit_count:
        out.append(accumulator & 0xFF)
    return bytes(out)


def gif_subblocks(data):
    out = bytearray()
    for start in range(0, len(data), 255):
        block = data[start:start + 255]
        out.append(len(block))
        out += block
    out.append(0)
    return bytes(out)


def gif_lzw_stream(indices, min_code_size=8):
    clear = 1 << min_code_size
    end = clear + 1
    width = min_code_size + 1
    codes = [clear]
    since_clear = 0
    for index in indices:
        codes.append(index)
        since_clear += 1
        if since_clear >= 100:
            codes.append(clear)
            since_clear = 0
    codes.append(end)
    return pack_lsb(codes, width)


def gif_animated(width, height, frames):
    out = bytearray()
    out += b"GIF89a"
    out += struct.pack("<HHBBB", width, height, 0xF7, 0, 0)  # 256-entry GCT
    palette = [(0, 0, 0), (255, 255, 255), (255, 0, 0), (0, 0, 255)]
    for i in range(256):
        out += bytes(palette[i] if i < len(palette) else (0, 0, 0))
    # NETSCAPE2.0 application extension: loop forever.
    out += b"\x21\xFF\x0B" + b"NETSCAPE2.0" + b"\x03\x01\x00\x00" + b"\x00"
    for delay, indices in frames:
        out += (
            b"\x21\xF9\x04"
            + bytes([0x04])  # disposal 1, no transparency
            + struct.pack("<H", delay)
            + b"\x00"  # transparent colour index
            + b"\x00"  # block terminator
        )
        out += b"\x2C" + struct.pack("<HHHHB", 0, 0, width, height, 0x00)
        out += bytes([8]) + gif_subblocks(gif_lzw_stream(indices, 8))
    out += b"\x3B"
    return bytes(out)


# --------------------------------------------------------------------------
# Little-endian TIFF encoder: two IFDs, each an 8-bit grayscale strip.
# --------------------------------------------------------------------------
def gray_page(width, height, seed):
    out = bytearray()
    for y in range(height):
        for x in range(width):
            out.append((x * 16 + y * 8 + seed) & 0xFF)
    return bytes(out)


def tiff_two_pages(page0, page1):
    entry_count = 10
    ifd_size = 2 + 12 * entry_count + 4
    ifd0_offset = 8
    strip0_offset = ifd0_offset + ifd_size
    ifd1_offset = strip0_offset + len(page0[2])
    strip1_offset = ifd1_offset + ifd_size

    def build_ifd(width, height, strip_offset, strip_length, next_ifd):
        entries = [
            (256, 4, 1, width),           # ImageWidth
            (257, 4, 1, height),          # ImageLength
            (258, 3, 1, 8),               # BitsPerSample
            (259, 3, 1, 1),               # Compression = none
            (262, 3, 1, 1),               # PhotometricInterpretation = BlackIsZero
            (273, 4, 1, strip_offset),    # StripOffsets
            (277, 3, 1, 1),               # SamplesPerPixel
            (278, 4, 1, height),          # RowsPerStrip
            (279, 4, 1, strip_length),    # StripByteCounts
            (284, 3, 1, 1),               # PlanarConfiguration = chunky
        ]
        blob = struct.pack("<H", entry_count)
        for tag, field_type, count, value in entries:
            blob += struct.pack("<HHI", tag, field_type, count)
            blob += struct.pack("<I", value)
        blob += struct.pack("<I", next_ifd)
        return blob

    ifd0 = build_ifd(page0[0], page0[1], strip0_offset, len(page0[2]), ifd1_offset)
    ifd1 = build_ifd(page1[0], page1[1], strip1_offset, len(page1[2]), 0)
    header = b"II" + struct.pack("<H", 42) + struct.pack("<I", ifd0_offset)
    return header + ifd0 + page0[2] + ifd1 + page1[2]


