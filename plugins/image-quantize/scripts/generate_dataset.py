def render_dataset_json(rows, real):
    real_files = []
    for entry in real.get("files", []):
        row = dict(entry)
        row["path"] = display_path(Path(entry["path"]), PACKAGE_ROOT)
        real_files.append(row)
    by_slot = {entry.get("slot"): entry for entry in real_files}
    return {
        "schema_version": 1,
        "generated_count": len(rows),
        "blocked_count": 0,
        "public_domain_count": len(real_files),
        "source": "synthetic (generated by committed scripts)",
        "license": LICENSE,
        "redistribution_permission": REDISTRIBUTION,
        "generated_fixtures": rows,
        "public_domain_fixtures": real_files,
        "section_9_3_coverage": [
            {
                "file": name,
                "category": category,
                "target_dimensions": dims,
                "filled_by": by_slot[name]["path"] if name in by_slot else None,
                "license": by_slot[name]["license"] if name in by_slot else None,
                "status": "FILLED" if name in by_slot else MISSING,
            }
            for name, category, dims, _description in USER_SUPPLIED
        ],
        "deviation_from_9_3": (
            "9.3 was amended on 2026-11-04 (Appendix C r9) to accept a recorded "
            "CC0-1.0 substitute when a user-owned original cannot be licensed. "
            "The twelve slots are filled from CC0-1.0 public-domain sources and "
            "in-code UI fixtures by owner decision, and every substitute is "
            "recorded as such. Licence terms are quoted and dated in the Markdown "
            "manifest; docs/dataset-real.json records the source page and the "
            "SHA-256 of every normalised file."
        ),
        "phase0_exit_gate": (
            "DATASET ITEM SATISFIED - 12 of 12 slots populated and 29 of 29 "
            "generated fixtures present. The other Phase 0 gate items are tracked "
            "in the Phase 0 report and are not claimed here."
        ),
    }


def write_bytes(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def main():
    parser = argparse.ArgumentParser(
        description="Generate the deterministic SPEC-003 Phase 0 image fixture dataset.")
    parser.add_argument("--out-dir", default=str(DEFAULT_OUT_DIR),
                        help="Directory for the generated image fixtures.")
    parser.add_argument("--manifest", default=str(DEFAULT_MANIFEST),
                        help="Path of the Markdown manifest to write.")
    args = parser.parse_args()

    out_dir = Path(args.out_dir)
    manifest_path = Path(args.manifest)
    dataset_json_path = manifest_path.parent / "dataset.json"
    real_record_path = manifest_path.parent / "dataset-real.json"

    if real_record_path.is_file():
        real = json.loads(real_record_path.read_text(encoding="utf-8"))
    else:
        # A fresh checkout without the fetched group must still render: the
        # generator reports the slots as missing rather than inventing rows.
        real = {"files": []}
        print(f"WARNING: {real_record_path} is absent; the 9.3 slots render as MISSING.")

    fixtures = build_png_fixtures() + build_multiframe_fixtures()

    rows = []
    for fixture in fixtures:
        data = fixture["data"]
        target = out_dir / fixture["filename"]
        write_bytes(target, data)
        rows.append({
            "path": display_path(target, PACKAGE_ROOT),
            "dimensions": fixture["dimensions"],
            "byte_size": len(data),
            "sha256": hashlib.sha256(data).hexdigest(),
            "source": SOURCE,
            "license": LICENSE,
            "redistribution_permission": REDISTRIBUTION,
            "description": fixture["description"],
        })

    # The animated WebP cannot be written by this standard-library-only
    # script. It is generated once by generate_animated_webp.py and copied
    # here so --out-dir still produces a complete set.
    webp_source = out_dir / WEBP_FILENAME
    if not webp_source.is_file():
        webp_source = DEFAULT_OUT_DIR / WEBP_FILENAME
    if not webp_source.is_file():
        raise SystemExit(
            f"MISSING: {webp_source}; run scripts/generate_animated_webp.py first")
    webp_data = webp_source.read_bytes()
    webp_target = out_dir / WEBP_FILENAME
    if webp_target != webp_source:
        write_bytes(webp_target, webp_data)
    rows.append({
        "path": display_path(webp_target, PACKAGE_ROOT),
        "dimensions": "16x16 (2 frames)",
        "byte_size": len(webp_data),
        "sha256": hashlib.sha256(webp_data).hexdigest(),
        "source": WEBP_SOURCE,
        "license": LICENSE,
        "redistribution_permission": REDISTRIBUTION,
        "description": (
            "2-frame lossless animated WebP (RIFF/ANIM/ANMF); exercises "
            "animated-container handling and the first-frame-only rule."
        ),
    })

    write_bytes(manifest_path, render_manifest(rows, real).encode("utf-8"))
    write_bytes(dataset_json_path,
                (json.dumps(render_dataset_json(rows, real), indent=2)
                 + "\n").encode("utf-8"))

    group_counts = {}
    for fixture in fixtures:
        group_counts[fixture["group"]] = group_counts.get(fixture["group"], 0) + 1
    group_counts["multiframe"] = group_counts.get("multiframe", 0) + 1

    print("Seer image quantization - SPEC-003 Phase 0 dataset generator")
    print(f"Package root : {PACKAGE_ROOT}")
    print(f"Output dir   : {out_dir}")
    print(f"Manifest     : {manifest_path}")
    print(f"Dataset JSON : {dataset_json_path}")
    print("")
    print(f"Generated fixtures: {len(rows)}")
    for group in sorted(group_counts):
        print(f"  {group}: {group_counts[group]}")
    print("")
    print(f"Generated fixtures: {len(rows)} (including the animated WebP)")
    filled = sum(1 for name, *_rest in USER_SUPPLIED
                 if name in {entry.get("slot") for entry in real.get("files", [])})
    print(f"Section 9.3 slots: {filled}/{len(USER_SUPPLIED)} filled "
          f"({len(real.get('files', []))} public-domain/project-owned files)")
    print("Phase 0 exit gate, dataset item only: 12/12 slots and 29/29 fixtures.")
    print("")
    print("Done.")


if __name__ == "__main__":
    main()
