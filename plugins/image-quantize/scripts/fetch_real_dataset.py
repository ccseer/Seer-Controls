class FetchError(RuntimeError):
    pass


def open_url(url: str, opener: urllib.request.OpenerDirector,
             timeout: int = 45, deadline: int = 240) -> bytes:
    """GET with a hard wall-clock cap.

    A socket timeout alone does not bound a transfer: a proxy that keeps
    trickling bytes never trips it. The chunked read below aborts the attempt
    once the total elapsed time passes ``deadline`` so a stalled tunnel is
    retried instead of hanging the whole run.
    """
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    last: Exception | None = None
    for attempt in range(DOWNLOAD_ATTEMPTS):
        started = time.monotonic()
        try:
            with opener.open(request, timeout=timeout) as response:
                # Scale the cap with the announced body size so a slow but
                # healthy link can finish a 40 MB original instead of being
                # cut off at a fixed wall-clock limit.
                length = int(response.headers.get("Content-Length") or 0)
                limit = max(deadline, length / 120_000 * 1.5 + 30)
                chunks = []
                while True:
                    if time.monotonic() - started > limit:
                        raise TimeoutError(f"transfer exceeded {limit:.0f}s")
                    block = response.read(65536)
                    if not block:
                        return b"".join(chunks)
                    chunks.append(block)
        except (urllib.error.URLError, TimeoutError, OSError) as exc:
            last = exc
            time.sleep(2 + 3 * attempt)
    raise FetchError(f"cannot fetch {url}: {last}")


def build_opener(proxy: str | None) -> urllib.request.OpenerDirector:
    if proxy:
        handler = urllib.request.ProxyHandler({"http": proxy, "https": proxy})
    else:
        # Ambient registry proxies turn a clear DNS failure into an opaque 502
        # from the tunnel, so the default is an explicit empty proxy map.
        handler = urllib.request.ProxyHandler({})
    return urllib.request.build_opener(handler)


def extmetadata(info: dict) -> dict:
    meta = info.get("extmetadata") or {}
    return meta if isinstance(meta, dict) else {}


def commons_api(params: dict, opener: urllib.request.OpenerDirector) -> dict:
    url = f"{API_URL}?{urllib.parse.urlencode(params)}"
    payload = json.loads(open_url(url, opener))
    if "warnings" in payload:
        raise FetchError(f"API rejected the query: {payload['warnings']}")
    return payload


def resolve_pinned(spec: PhotoSpec, opener: urllib.request.OpenerDirector) -> dict:
    params = {
        "action": "query",
        "titles": spec.title,
        "prop": "imageinfo",
        "iiprop": "url|size|mime|extmetadata",
        "iiextmetadatafilter": "License|LicenseShortName|Artist|Credit",
        "format": "json",
        "formatversion": "2",
    }
    pages = commons_api(params, opener).get("query", {}).get("pages", [])
    if not pages or pages[0].get("missing"):
        raise FetchError(f"{spec.slot}: pinned file is gone from Commons: {spec.title}")
    info = (pages[0].get("imageinfo") or [None])[0]
    if not info:
        raise FetchError(f"{spec.slot}: no imageinfo for {spec.title}")

    licence = (extmetadata(info).get("License") or {}).get("value", "").strip().lower()
    if licence != CC0_LICENSE_KEY:
        raise FetchError(
            f"{spec.slot}: licence is {licence or 'unknown'}, expected CC0; refusing to use it"
        )
    if info.get("mime") not in ("image/jpeg", "image/png"):
        raise FetchError(f"{spec.slot}: unsupported MIME {info.get('mime')}")
    if info.get("width", 0) < spec.min_width or info.get("height", 0) < spec.min_height:
        raise FetchError(
            f"{spec.slot}: {info['width']}x{info['height']} is below the required "
            f"{spec.min_width}x{spec.min_height}"
        )
    if not MIN_ORIGINAL_BYTES <= info.get("size", 0) <= MAX_ORIGINAL_BYTES:
        raise FetchError(f"{spec.slot}: original size {info.get('size')} bytes is out of budget")
    return info


def search_shortlist(spec: PhotoSpec, opener: urllib.request.OpenerDirector) -> list[str]:
    params = {
        "action": "query",
        "generator": "search",
        "gsrsearch": (f"filetype:bitmap filew:>{spec.min_width} "
                      f"fileh:>{spec.min_height} {spec.query}"),
        "gsrnamespace": "6",
        "gsrlimit": "40",
        "prop": "imageinfo",
        "iiprop": "size|mime|extmetadata",
        "iiextmetadatafilter": "License",
        "format": "json",
        "formatversion": "2",
    }
    pages = commons_api(params, opener).get("query", {}).get("pages", [])
    rows = []
    for page in pages:
        info = (page.get("imageinfo") or [{}])[0]
        licence = (extmetadata(info).get("License") or {}).get("value", "").lower()
        if licence != CC0_LICENSE_KEY or info.get("mime") not in ("image/jpeg", "image/png"):
            continue
        rows.append(f"    {info.get('width')}x{info.get('height')} "
                    f"{info.get('size', 0) / 1e6:.1f} MB  {page['title']}")
    return rows


def normalize_photo(raw: bytes, target: tuple[int, int], out_path: Path) -> None:
    with Image.open(io.BytesIO(raw)) as source:
        oriented = ImageOps.exif_transpose(source)
        icc = oriented.info.get("icc_profile") or source.info.get("icc_profile")
        rgb = oriented.convert("RGB")
        if icc:
            try:
                rgb = ImageCms.profileToProfile(
                    rgb,
                    ImageCms.ImageCmsProfile(io.BytesIO(icc)),
                    SRGB_PROFILE,
                    outputMode="RGB",
                )
            except (ImageCms.PyCMSError, OSError, ValueError):
                # An unreadable profile is not a licence problem; the pixels
                # were already decoded as sRGB by convert("RGB").
                pass
        fitted = ImageOps.fit(rgb, target, method=Image.Resampling.LANCZOS)
        clean = Image.frombytes("RGB", fitted.size, fitted.tobytes())
        clean.save(out_path, format="PNG", optimize=False)


