#!/usr/bin/env python3
"""Fetch and normalise the 12 non-synthetic SPEC-003 fixtures.

Two groups are produced:

* eight CC0 photographs pulled from Wikimedia Commons. The source file is
  pinned by title, and its licence is re-verified against the API's
  machine-readable ``extmetadata.License`` field on every run, so a licence
  change upstream fails the run instead of silently entering the manifest;
* four project-owned UI fixtures drawn deterministically with Pillow, so the
  third-party-UI-artwork ban of SPEC-003 9.1 cannot be violated by
  construction.

Normalisation for every photograph: bake the EXIF orientation, convert the
embedded ICC profile to sRGB, resample to the target size, then re-encode as an
8-bit RGB PNG rebuilt from raw bytes, so no EXIF, ICC or text chunk survives.

Titles are pinned rather than searched because Commons relevance ranking cannot
tell a sky gradient from a city skyline; ``--search`` re-runs the query that
built each shortlist so the pin can be re-reviewed when it goes stale.

Requires Pillow. Run ``--dry-run`` to resolve and licence-check without
downloading, ``--verify`` to re-hash the files already on disk.

Outputs
-------
* 12 PNG files under ``test/data/real``.
* ``docs/dataset-real.json``: dimensions, byte size, SHA-256, source page,
  licence and the UTC access date per file.
* A Markdown table on stdout for ``docs/quantization-dataset.md``.
"""

