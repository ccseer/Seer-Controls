def png_facts(path: Path) -> dict:
    """Chunk list, bit depth and colour type read from the file, not from Pillow."""
    data = path.read_bytes()
    if not data.startswith(b"\x89PNG\r\n\x1a\n"):
        raise FetchError(f"{path.name}: not a PNG")
    offset, chunks, bit_depth, colour_type = 8, [], None, None
    while offset < len(data):
        length = int.from_bytes(data[offset : offset + 4], "big")
        kind = data[offset + 4 : offset + 8].decode("ascii")
        if kind == "IHDR":
            bit_depth = data[offset + 16]
            colour_type = data[offset + 17]
        chunks.append(kind)
        offset += 12 + length
    with Image.open(path) as image:
        width, height = image.size
        mode = image.mode
    return {
        "width": width,
        "height": height,
        "mode": mode,
        "bit_depth": bit_depth,
        "colour_type": colour_type,
        "chunks": chunks,
    }


def sha256_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def record_path(path: Path) -> str:
    """Package-relative when the file lives in the package, absolute otherwise.

    A machine-specific absolute path in the record would make the manifest
    unreproducible on the next checkout, so the in-tree default stays relative.
    """
    try:
        return path.resolve().relative_to(PACKAGE_ROOT).as_posix()
    except ValueError:
        return path.resolve().as_posix()


def check_file(path: Path, expected_dimensions: str, expected_sha: str) -> list[str]:
    problems = []
    facts = png_facts(path)
    if facts["bit_depth"] != 8:
        problems.append(f"bit depth {facts['bit_depth']} != 8")
    if facts["mode"] not in ("RGB", "RGBA"):
        problems.append(f"mode {facts['mode']} is not 8-bit RGB/RGBA")
    if facts["colour_type"] not in (2, 6):
        problems.append(f"PNG colour type {facts['colour_type']} is palettised or gray")
    extra = sorted(set(facts["chunks"]) - {"IHDR", "IDAT", "IEND"})
    if extra:
        problems.append(f"ancillary chunks present: {', '.join(extra)}")
    if sha256_of(path) != expected_sha:
        problems.append("sha256 mismatch")
    if f"{facts['width']}x{facts['height']}" != expected_dimensions:
        problems.append(f"dimensions {facts['width']}x{facts['height']} != {expected_dimensions}")
    return problems


def verify(directory: Path, record_path: Path) -> int:
    record = json.loads(record_path.read_text(encoding="utf-8"))
    failures = 0
    for entry in record["files"]:
        path = directory / Path(entry["path"]).name
        if not path.is_file():
            print(f"MISSING {path.name}")
            failures += 1
            continue
        problems = check_file(path, entry["dimensions"], entry["sha256"])
        print(f"{'OK  ' if not problems else 'FAIL'} {path.name}: "
              f"{'; '.join(problems) if problems else 'clean'}")
        failures += len(problems)
    print(f"FAILURES: {failures}")
    return 1 if failures else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="fetch_real_dataset.py",
        description="Fetch the eight CC0 photographs and draw the four UI "
                    "fixtures for the SPEC-003 Phase 0 dataset.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    parser.add_argument("--record", type=Path, default=DEFAULT_RECORD)
    parser.add_argument("--proxy", default=None,
                        help="explicit HTTP(S) proxy, e.g. http://127.0.0.1:7897; "
                             "when omitted no ambient proxy is used")
    parser.add_argument("--dry-run", action="store_true",
                        help="resolve and licence-check the pins without downloading")
    parser.add_argument("--verify", action="store_true",
                        help="re-hash existing files against the recorded manifest")
    parser.add_argument("--search", metavar="SLOT", default=None,
                        help="print the CC0 shortlist for a slot, to re-review a pin")
    parser.add_argument("--jobs", type=int, default=4,
                        help="parallel download connections (default 4)")
    parser.add_argument("--skip-photos", action="store_true")
    args = parser.parse_args(argv)

    if args.verify:
        return verify(args.out_dir, args.record)

    opener = build_opener(args.proxy)

    if args.search:
        matches = [spec for spec in PHOTO_SPECS if spec.slot == args.search]
        if not matches:
            print(f"unknown slot {args.search}; known: "
                  f"{', '.join(spec.slot for spec in PHOTO_SPECS)}", file=sys.stderr)
            return 2
        print(f"shortlist for {args.search} (query: {matches[0].query})")
        for row in search_shortlist(matches[0], opener):
            print(row)
        return 0

    args.out_dir.mkdir(parents=True, exist_ok=True)
    access_date = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d")
    entries: list[dict] = []

    print("[1/2] drawing the four project-owned UI fixtures")
    for name, slot, description in build_ui_fixtures(args.out_dir):
        path = args.out_dir / name
        facts = png_facts(path)
        entries.append({
            "path": record_path(path),
            "slot": slot,
            "dimensions": f"{facts['width']}x{facts['height']}",
            "byte_size": path.stat().st_size,
            "sha256": sha256_of(path),
            "source": GENERATED_SOURCE,
            "license": LICENSE,
            "redistribution_permission": "unrestricted",
            "source_url": None,
            "access_date": access_date,
            "description": description,
        })
        print(f"  OK {name} ({entries[-1]['dimensions']}, {entries[-1]['byte_size']} bytes)")

    if args.skip_photos:
        specs: tuple[PhotoSpec, ...] = ()
    else:
        specs = PHOTO_SPECS

    if specs:
        print("[2/2] resolving and normalising the eight CC0 photographs")
    resolved: list[tuple[PhotoSpec, dict]] = []
    for spec in specs:
        info = resolve_pinned(spec, opener)
        print(f"  {spec.filename}: {spec.title} "
              f"({info['width']}x{info['height']}, {info['size'] / 1e6:.1f} MB, CC0)")
        resolved.append((spec, info))

    if not args.dry_run and resolved:
        # Downloads overlap because a single tunnel to the Commons origin can
        # stall for minutes; decoding stays serial because the 8K intermediate
        # alone is several hundred megabytes of RGB.
        with ThreadPoolExecutor(max_workers=args.jobs) as pool:
            futures = {
                pool.submit(open_url, info["url"], opener): spec
                for spec, info in resolved
            }
            payloads: dict[str, bytes] = {}
            for future in as_completed(futures):
                spec = futures[future]
                payloads[spec.filename] = future.result()
                print(f"    downloaded {spec.filename} "
                      f"({len(payloads[spec.filename]) / 1e6:.1f} MB)")
    else:
        payloads = {}

    for spec, info in resolved:
        if args.dry_run:
            continue
        out_path = args.out_dir / spec.filename
        normalize_photo(payloads[spec.filename], spec.target, out_path)
        facts = png_facts(out_path)
        entries.append({
            "path": record_path(out_path),
            "slot": spec.slot,
            "dimensions": f"{facts['width']}x{facts['height']}",
            "byte_size": out_path.stat().st_size,
            "sha256": sha256_of(out_path),
            "source": f"Wikimedia Commons: {spec.title}",
            "license": LICENSE,
            "redistribution_permission": "unrestricted",
            "source_url": info.get("descriptionurl", info["url"]),
            "access_date": access_date,
            "description": spec.description,
        })
        print(f"    -> {out_path.name} {entries[-1]['dimensions']} "
              f"{entries[-1]['byte_size'] / 1e6:.2f} MB")

    if args.dry_run:
        return 0

    record = {
        "schema_version": 1,
        "access_date": access_date,
        "license": LICENSE,
        "note": "Non-synthetic Phase 0 fixtures. Photographs are CC0 originals "
                "from Wikimedia Commons, normalised to 8-bit sRGB PNG; the four "
                "UI fixtures are project-owned and drawn in code.",
        "files": entries,
    }
    args.record.parent.mkdir(parents=True, exist_ok=True)
    # Byte write: text mode would translate the newlines to CRLF on Windows,
    # and the package forbids CRLF in text artefacts.
    args.record.write_bytes((json.dumps(record, indent=2) + "\n").encode("utf-8"))

    print("\n| path | dimensions | byte size | SHA-256 | source | license | "
          "redistribution permission | description |")
    print("| --- | --- | --- | --- | --- | --- | --- | --- |")
    for entry in entries:
        print(f"| `{Path(entry['path']).name}` | {entry['dimensions']} | "
              f"{entry['byte_size']} | {entry['sha256']} | {entry['source']} | "
              f"{entry['license']} | {entry['redistribution_permission']} | "
              f"{entry['description']} |")
    print(f"\nrecord written to {args.record}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
